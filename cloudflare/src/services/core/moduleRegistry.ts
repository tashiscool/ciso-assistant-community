export function findModuleCatalogEntry(moduleKey: string) {
  const normalized = moduleKey.trim().toLowerCase();
  return MODULE_CATALOG.find(
    (entry) =>
      entry.moduleKey === normalized ||
      entry.aliases?.some((alias) => alias.trim().toLowerCase() === normalized),
  );
}

export function listSharedWorkspaceModules() {
  return MODULE_CATALOG.filter((entry) => entry.implementationType === 'shared-workspace');
}

export function listTemplateWorkspaceModules() {
  return MODULE_CATALOG.filter((entry) => entry.implementationType === 'template-workspace');
}

export function listScaleModuleCatalogEntries() {
  return MODULE_CATALOG.filter((entry) => SCALE_MD_MODULE_KEY_SET.has(entry.moduleKey));
}
